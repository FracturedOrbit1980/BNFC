function drill(input: DrillInput): DrillTemplate {
  const place = PLACEMENT[input.id];
  if (!place) throw new Error(`Missing age and skill for ${input.id}`);
  const outfield = input.players.attackers + input.players.defenders + input.players.neutrals;
  return {
    id: input.id,
    title: drillTitle(input.type, input.focus, input.playerSetup, input.constraint),
    isClubOfficial: true,
    targetAgeGroup: input.ageBand,
    moment: input.moment,
    drillType: input.type,
    level: levelFor(input.ageBand, input.license),
    focus: input.focus,
    playerSetup: input.playerSetup,
    constraint: input.constraint,
    dimensions: `${input.length}x${input.width}m`,
    workRest: input.workRest,
    repetitions: input.repetitions,
    players: { ...input.players },
    equipment: input.equipment,
    diagram: input.diagram,
    pitchSetup: input.pitchSetup,
    instructions: input.instructions,
    coachingPoints: input.coachingPoints,
    progressions: input.progressions,
    tags: input.tags,
    licenseLevel: input.license,
    ageBand: input.ageBand,
    youthAge: place.youthAge,
    skillLevel: place.skillLevel,
    minPlayers: outfield,
    maxPlayers: outfield,
    pitchLengthM: input.length,
    pitchWidthM: input.width,
    defaultDurationSeconds: input.minutes * 60,
    videoUrl: "",
    videoName: "",
  };
}

