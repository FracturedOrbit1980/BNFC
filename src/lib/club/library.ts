function levelFor(ageBand: AgeBand, license: LicenseLevel): DrillLevel {
  if (license === "UEFA Pro") return "Pro";
  if (ageBand === "senior" || license === "UEFA A") return "Senior Amateur";
  if (ageBand === "U14-U16") return "Youth U13-16";
  if (ageBand === "U8-U10") return "Grassroots";
  return "Youth U9-12";
}

